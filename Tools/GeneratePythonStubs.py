"""Generates Python/_bellows.pyi, the type stub for the engine's native `_bellows` module.

Editors (and MageCap Forge) read the stub for completion, hover help and type checking, since the
native module has no Python source. It is generated from the running module's own signatures, so it
always matches ScriptApiDefinition.h and the Python-only extras in ScriptBindings.cpp.

Run it inside the editor, which embeds the module:

    BellowsEditor --headless --no-agent-server --run-script Tools/GeneratePythonStubs.py --exit

The editor automation test (BellowsEditorAutomationTests) fails when the committed stub is out of date.
"""

import ast
import pathlib
import re

HEADER = '''"""Type stub for MageCap Bellows' native module `_bellows` (re-exported by the `bellows` package).

Generated by Tools/GeneratePythonStubs.py - do not edit by hand.
"""

from __future__ import annotations

import enum
import typing

'''

STUB_PATH = pathlib.Path(__file__).resolve().parent.parent / "Python" / "_bellows.pyi"

# pybind11 spells some types in ways a reader or type checker does not need.
_TYPE_REPLACEMENTS = (
    ("typing.SupportsFloat | typing.SupportsIndex", "float"),
    ("typing.SupportsInt | typing.SupportsIndex", "int"),
    ("_bellows.", ""),
    ("collections.abc.", "typing."),
)

# Bare generics pybind11 prints, given the item types the engine uses (vector components, maps by name).
_GENERIC_DEFAULTS = (
    (r"\btyping\.(Sequence|Iterator|Iterable)\b(?!\[)", r"typing.\1[float]"),
    (r"\bdict\b(?!\[)", "dict[str, typing.Any]"),
    (r"\blist\b(?!\[)", "list[typing.Any]"),
)

_SIGNATURE = re.compile(r"^(?P<name>[A-Za-z_][A-Za-z0-9_]*)?\((?P<args>.*)\)(?:\s*->\s*(?P<ret>.+))?$")


def _clean_type(text):
    text = text.strip()
    for old, new in _TYPE_REPLACEMENTS:
        text = text.replace(old, new)
    for pattern, replacement in _GENERIC_DEFAULTS:
        text = re.sub(pattern, replacement, text)
    return text


def _widen_parameter(annotation):
    """Vector parameters also take tuples and lists, e.g. entity.position = (0, 1, 0)."""
    if "typing.Sequence" in annotation:
        return annotation
    return re.sub(r"\bVec([234])\b", r"Vec\1 | typing.Sequence[float]", annotation)


def _split_top_level(text):
    """Splits on commas that are not inside brackets or quotes."""
    parts, depth, quote, current = [], 0, None, ""
    for char in text:
        if quote:
            current += char
            if char == quote:
                quote = None
            continue
        if char in "'\"":
            quote = char
        elif char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(current)
            current = ""
            continue
        current += char
    if current.strip():
        parts.append(current)
    return [part.strip() for part in parts]


def _is_expression(text):
    try:
        ast.parse(text, mode="eval")
        return True
    except SyntaxError:
        return False


def _clean_argument(argument, first, is_method):
    if argument in ("*", "/"):
        return argument
    if argument.startswith("*"):
        return argument if ":" in argument else argument + ": typing.Any"
    name, _, rest = argument.partition(":")
    name = name.strip()
    if first and is_method:
        return "self"
    annotation, default = rest, None
    if "=" in rest:
        annotation, default = rest.split("=", 1)
    result = name
    if annotation.strip():
        result += ": " + _widen_parameter(_clean_type(annotation))
    if default is not None:
        default = default.strip()
        # Defaults pybind11 prints as "<Key.Space: 32>" or object reprs are not valid Python.
        result += " = " + (default if _is_expression(default) and not default.startswith("<") else "...")
    return result


def _parse_signature(line, is_method):
    match = _SIGNATURE.match(line.strip())
    if not match:
        return None
    arguments = [_clean_argument(arg, index == 0, is_method) for index, arg in enumerate(_split_top_level(match.group("args")))]
    # Comparisons accept any object (returning False for other types), as Python requires.
    if match.group("name") in ("__eq__", "__ne__") and len(arguments) == 2:
        arguments[1] = arguments[1].split(":")[0] + ": object"
    if is_method and not arguments:
        arguments = ["self"]
    returns = _clean_type(match.group("ret") or "None")
    return f"({', '.join(arguments)}) -> {returns}"


def _signatures(doc, name, is_method):
    """Every signature in a pybind11 docstring (several when the function is overloaded), plus the description."""
    lines = (doc or "").splitlines()
    if not lines:
        return [f"(self) -> typing.Any" if is_method else "(*args: typing.Any, **kwargs: typing.Any) -> typing.Any"], ""
    if len(lines) > 1 and lines[1].strip() == "Overloaded function.":
        signatures = []
        for line in lines[2:]:
            found = re.match(r"^\d+\.\s+(.*)$", line.strip())
            if found:
                parsed = _parse_signature(found.group(1), is_method)
                if parsed:
                    signatures.append(parsed)
        return signatures, ""
    parsed = _parse_signature(lines[0], is_method)
    description = "\n".join(lines[1:]).strip()
    if parsed is None:
        return [f"(self) -> typing.Any" if is_method else "(*args: typing.Any, **kwargs: typing.Any) -> typing.Any"], (doc or "").strip()
    return [parsed], description


def _docstring(text, indent):
    if not text:
        return ""
    text = text.replace('"""', "'''").replace("\\", "\\\\")
    return f'{indent}"""{text}"""\n'


def _function(name, obj, indent, is_method, decorator=None):
    signatures, description = _signatures(getattr(obj, "__doc__", None), name, is_method)
    out = ""
    for signature in signatures:
        if len(signatures) > 1:
            out += f"{indent}@typing.overload\n"
        if decorator:
            out += f"{indent}@{decorator}\n"
        if description and len(signatures) == 1:
            out += f"{indent}def {name}{signature}:\n{_docstring(description, indent + '    ')}"
        else:
            # In-place operators are narrower than their plain forms (v *= 2 works, v *= other_vector does not), which type checkers flag.
            ignore = "  # type: ignore[misc]" if name in ("__imul__", "__itruediv__") else ""
            out += f"{indent}def {name}{signature}: ...{ignore}\n"
    return out


def _property(name, prop, indent):
    getter_doc = getattr(prop.fget, "__doc__", "") or ""
    match = re.search(r"->\s*(.+)$", getter_doc.splitlines()[0]) if getter_doc else None
    annotation = _clean_type(match.group(1)) if match else "typing.Any"
    description = (prop.__doc__ or "").strip()
    if description.startswith("(self"):
        description = ""
    out = f"{indent}@property\n{indent}def {name}(self) -> {annotation}:"
    out += f"\n{_docstring(description, indent + '    ')}" if description else " ...\n"
    if prop.fset is not None:
        # The setter may accept more than the getter returns (a material object or a path, say).
        setter_doc = getattr(prop.fset, "__doc__", "") or ""
        setter = re.match(r"^\([^,]*,\s*\w+:\s*(.+)\)\s*->", setter_doc.splitlines()[0]) if setter_doc else None
        value_type = _widen_parameter(_clean_type(setter.group(1))) if setter else annotation
        out += f"{indent}@{name}.setter\n{indent}def {name}(self, value: {value_type}) -> None: ...\n"
    return out


def _is_enum(cls):
    return hasattr(cls, "__members__") and isinstance(getattr(cls, "__members__"), dict)


def _enum(name, cls):
    out = f"class {name}(enum.IntEnum):\n"
    out += _docstring((cls.__doc__ or "").strip().splitlines()[0] if cls.__doc__ else "", "    ")
    for member, value in cls.__members__.items():
        out += f"    {member} = {int(value)}\n"
    return out


def _class(name, cls):
    if _is_enum(cls):
        return _enum(name, cls)
    out = f"class {name}:\n"
    doc = (cls.__doc__ or "").strip()
    if doc:
        out += _docstring(doc, "    ")
    body = ""
    for member, value in vars(cls).items():
        if member.startswith("_pybind11") or member in ("__doc__", "__module__", "__dict__", "__weakref__"):
            continue
        kind = type(value).__name__
        if kind == "property":
            body += _property(member, value, "    ")
        elif kind == "staticmethod":
            body += _function(member, value.__func__, "    ", False, "staticmethod")
        elif kind in ("instancemethod", "builtin_function_or_method", "function"):
            if member.startswith("__") and member != "__init__" and not (getattr(value, "__doc__", "") or "").startswith(member + "("):
                continue
            body += _function(member, value, "    ", True)
        elif not member.startswith("_") and not callable(value):
            body += f"    {member}: {type(value).__name__}\n"
    return out + (body or "    ...\n")


def generate():
    """Returns the stub text for the running `_bellows` module."""
    import _bellows

    classes, functions, constants = [], [], []
    for name in sorted(vars(_bellows)):
        if name.startswith("_"):
            continue
        value = getattr(_bellows, name)
        if isinstance(value, type):
            classes.append((name, value))
        elif callable(value):
            functions.append((name, value))
        elif type(value).__name__ != "module":  # bellows.editor exists only inside the editor
            constants.append((name, value))

    # Enums and simple value types first, so the rest of the file reads top-down.
    classes.sort(key=lambda item: (not _is_enum(item[1]), item[0]))
    parts = [HEADER]
    for name, value in constants:
        parts.append(f"{name}: {type(value).__name__}\n")
    for name, cls in classes:
        parts.append("\n\n" + _class(name, cls))
    parts.append("\n")
    for name, function in functions:
        parts.append("\n" + _function(name, function, "", False))
    text = "".join(parts).rstrip() + "\n"
    ast.parse(text)  # The stub must at least be valid Python.
    return text


def main():
    STUB_PATH.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"Wrote {STUB_PATH}")


if __name__ == "__main__":
    main()
