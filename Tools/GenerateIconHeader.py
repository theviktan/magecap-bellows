"""Generates BellowsEditor/Source/IconsLucide.h from the Lucide font's codepoint map.

Usage: python Tools/GenerateIconHeader.py

Only the icons listed in ICONS are emitted, so the header stays small and every icon the
editor uses is reviewed. Add a name from Resources/Fonts/Lucide/codepoints.json and rerun.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CODEPOINTS = ROOT / "Resources" / "Fonts" / "Lucide" / "codepoints.json"
OUTPUT = ROOT / "BellowsEditor" / "Source" / "IconsLucide.h"

ICONS = [
    "play", "pause", "square", "step-forward", "box", "boxes", "folder", "folder-open", "folder-plus", "file", "file-code",
    "file-plus", "image", "sun", "lightbulb", "camera", "plus", "minus", "trash-2", "copy", "search", "settings",
    "eye", "eye-off", "move", "rotate-3d", "scale-3d", "globe", "layers", "terminal", "save", "undo-2", "redo-2",
    "chevron-right", "chevron-down", "chevron-left", "x", "circle", "music", "volume-2", "atom", "code", "cuboid",
    "orbit", "grid-3x3", "mountain", "flame", "package", "list-tree", "sliders-horizontal", "info", "triangle-alert",
    "circle-x", "cpu", "monitor", "magnet", "hand", "mouse-pointer-2", "scan", "refresh-cw", "download", "upload",
    "link", "zap", "cloud", "film", "gamepad-2", "file-json", "braces", "lock", "unlock", "house", "ellipsis",
    "ellipsis-vertical", "circle-check", "filter", "arrow-up", "maximize-2", "minimize-2", "palette", "shapes",
    "sparkles", "pencil", "rocket", "bot", "folder-input", "external-link", "scroll-text", "aperture", "focus",
    "crosshair", "flashlight", "cone", "cylinder", "panel-left", "layout-grid", "activity", "gauge", "arrow-left",
    "moon", "circle-dot", "clapperboard", "square-function", "book-open", "paperclip", "unlink", "file-text",
    "save-all", "star", "bug", "redo-dot", "arrow-down-to-dot", "arrow-up-from-dot", "list-x", "type", "file-type",
    "mouse-pointer-click", "square-check", "chevrons-up-down", "text-cursor-input", "layout-template", "person-standing", "route", "footprints", "diamond",
    "anchor", "user", "users", "flag", "swords", "trees", "layout", "arrow-down", "pin", "pin-off", "sticker",
]

def main():
    codepoints = json.loads(CODEPOINTS.read_text(encoding="utf-8"))
    lines = [
        "#pragma once",
        "",
        "// Lucide icon glyphs (https://lucide.dev, ISC license) as UTF-8 string literals.",
        "// Generated by Tools/GenerateIconHeader.py - do not edit by hand.",
        "",
        "#define ICON_LUCIDE_MIN 0x%04X" % min(codepoints[name] for name in ICONS),
        "#define ICON_LUCIDE_MAX 0x%04X" % max(codepoints[name] for name in ICONS),
        "",
    ]
    for name in ICONS:
        code = codepoints[name]
        utf8 = chr(code).encode("utf-8")
        literal = "".join("\\x%02x" % b for b in utf8)
        macro = "ICON_" + name.upper().replace("-", "_")
        lines.append('#define %-32s "%s"\t// U+%04X' % (macro, literal, code))
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote %d icons to %s" % (len(ICONS), OUTPUT))

if __name__ == "__main__":
    main()
