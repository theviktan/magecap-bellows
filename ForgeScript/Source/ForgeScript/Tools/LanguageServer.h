#pragma once

#include "ForgeScript/Tools/Json.h"

#include <filesystem>
#include <iosfwd>
#include <map>
#include <string>
#include <vector>

namespace ForgeScript {

	// 'forgescript --lsp': a Language Server Protocol 3.17 server over standard input and output, for
	// MageCap Forge, the Bellows Script Editor and other editors. It offers:
	//   diagnostics (pushed after every open and change, from VM::FindMistakes),
	//   completion (keywords, built-ins, the engine API, the script's own names, scripts it uses),
	//   hover (signatures and docs), and go to definition (in the file and through 'use').
	// Documents are synced in full. Positions are in UTF-16 code units, as LSP requires. 'use' resolves
	// by the engine's rule (FindUseFolder), preferring the text of documents open in the editor.
	//
	// The engine's functions, types and phrases come from a JSON description (forgescript-api.json,
	// generated by MageCap Bellows); without one, the server knows only the language itself.
	class LanguageServer
	{
	public:
		struct Options
		{
			std::filesystem::path ApiFile;   // empty: no engine API
		};

		explicit LanguageServer(Options options);

		// Serves framed messages from 'in' until 'exit' or the end of the input. Returns the process exit
		// code: 0 after shutdown then exit, 1 otherwise (as LSP asks).
		int Run(std::istream& in, std::ostream& out);

		// Handles one message and returns what to send back: a response for a request, plus any
		// notifications (diagnostics). Used by Run, and directly by tests.
		std::vector<Json> Handle(const Json& message);

		bool ExitRequested() const { return m_ExitRequested; }
		int ExitCode() const { return m_ShutdownRequested ? 0 : 1; }

		// Content-Length framing. ReadMessage returns false at the end of the input or on a broken header.
		static bool ReadMessage(std::istream& in, std::string& outBody);
		static void WriteMessage(std::ostream& out, const std::string& body);

		// file:// URIs, with percent-encoding, and Windows drive letters (file:///C:/Games/a.forge).
		static bool UriToPath(const std::string& uri, std::filesystem::path& outPath);
		static std::string PathToUri(const std::filesystem::path& path);

	public:
		// A name defined in a script, found from its tokens without running it.
		struct Symbol
		{
			enum class Kind { Function, Phrase, KindType, Constant, Variable, Parameter, Module };

			Kind SymbolKind = Kind::Variable;
			std::string Name;        // for phrases, the whole pattern: "heal (target) by (amount)"
			std::string Signature;   // "function heal(target, amount)"
			std::string Doc;         // the '#' comment lines right above the definition
			std::string Owner;       // the kind a function or field belongs to, or the alias of a 'use'
			std::string File;        // the module path for 'use' (Kind::Module) and its definitions
			int Line = 0;            // 1-based, as in the lexer
			int Column = 0;          // 1-based byte column
			int Length = 0;          // bytes
		};

	private:
		struct Document
		{
			std::string Text;
			std::filesystem::path Path;
			double Version = 0;
		};

		struct ApiFunction
		{
			std::string Name;
			std::string Signature;
			std::string Returns;
			std::string Doc;
		};

		struct ApiMember
		{
			std::string Name;
			std::string Signature;
			std::string Type;   // a property's type, or a method's return type
			std::string Doc;
			bool IsProperty = false;
		};

		struct ApiType
		{
			std::string Name;
			std::string Doc;
			std::vector<ApiMember> Members;
		};

		struct ApiPhrase
		{
			std::string Pattern;
			std::string Returns;
			std::string Doc;
		};

	private:
		Json Initialize(const Json& params);
		Json Completion(const Json& params);
		Json Hover(const Json& params);
		Json Definition(const Json& params);
		Json PublishDiagnostics(const std::string& uri);

		void LoadApi(const std::filesystem::path& file);
		bool ReadScriptForUse(const std::filesystem::path& path, std::string& outSource) const;
		std::vector<Symbol> UsedSymbols(const std::filesystem::path& scriptPath, const std::string& source) const;
		const Document* FindDocument(const std::string& uri) const;

	private:
		Options m_Options;
		std::map<std::string, Document> m_Documents;
		std::vector<ApiFunction> m_ApiFunctions;
		std::vector<ApiType> m_ApiTypes;
		std::vector<ApiPhrase> m_ApiPhrases;
		std::string m_ApiError;
		bool m_Initialized = false;
		bool m_ShutdownRequested = false;
		bool m_ExitRequested = false;
	};

	// The definitions in a script (functions, phrases, kinds, constants, variables, parameters and
	// 'use' lines), in order. Works on scripts with mistakes too.
	std::vector<LanguageServer::Symbol> FindScriptSymbols(const std::string& source);

}
