#include "ForgeScript/Compiler/Compiler.h"
#include "ForgeScript/Tools/Json.h"

#include <filesystem>
#include <iosfwd>
#include <map>
#include <set>
#include <string>
#include <vector>

namespace ForgeScript {

	// 'forgescript --lsp': a Language Server Protocol 3.17 server over standard input and output, for
	// MageCap Forge, the Bellows Script Editor and other editors. It offers:
	//   diagnostics (pushed after every open and change, from VM::FindMistakes),
	//   completion (keywords, built-ins, the engine API, the script's own names, scripts it uses),
	//   hover (signatures and docs), and go to definition (in the file and through 'use').
	// Documents are synced in full. Positions are in UTF-16 code units, as LSP requires. 'use' resolves
	// by the engine's rule (FindUseFolder), preferring the text of documents open in the editor.
	//
	// The engine's functions, types and phrases come from a JSON description (forgescript-api.json,
	// generated by MageCap Bellows); without one, the server knows only the language itself.
	class LanguageServer
	{
	public:
		struct Options
		{
			std::filesystem::path ApiFile;   // empty: no engine API
		};

		explicit LanguageServer(Options options);

		// Serves framed messages from 'in' until 'exit' or the end of the input. Returns the process exit
		// code: 0 after shutdown then exit, 1 otherwise (as LSP asks).
		int Run(std::istream& in, std::ostream& out);

		// Handles one message and returns what to send back: a response for a request, plus any
		// notifications (diagnostics). Used by Run, and directly by tests.
		std::vector<Json> Handle(const Json& message);

		// The checks behind the diagnostics, also used by 'forgescript --check': the mistakes, and the
		// warnings, of a script's text, with the engine's phrases and functions known. 'path' places the
		// script, for its messages and to find the scripts it uses.
		std::vector<CompileError> FindMistakesIn(const std::filesystem::path& path, const std::string& text) const;
		std::vector<CompileError> FindWarningsIn(const std::filesystem::path& path, const std::string& text) const;
		// Why the engine API description could not be read; empty when it was, or none was given.
		const std::string& GetApiError() const { return m_ApiError; }

		bool ExitRequested() const { return m_ExitRequested; }
		int ExitCode() const { return m_ShutdownRequested ? 0 : 1; }

		// Content-Length framing. ReadMessage returns false at the end of the input or on a broken header.
		static bool ReadMessage(std::istream& in, std::string& outBody);
		static void WriteMessage(std::ostream& out, const std::string& body);

		// file:// URIs, with percent-encoding, and Windows drive letters (file:///C:/Games/a.forge).
		static bool UriToPath(const std::string& uri, std::filesystem::path& outPath);
		static std::string PathToUri(const std::filesystem::path& path);

	public:
		// A name defined in a script, found from its tokens without running it.
		struct Symbol
		{
			enum class Kind { Function, Phrase, KindType, Constant, Variable, Parameter, Module };

			Kind SymbolKind = Kind::Variable;
			std::string Name;        // for phrases, the whole pattern: "heal (target) by (amount)"
			std::string Signature;   // "function heal(target, amount)"
			std::string Doc;         // the '#' comment lines right above the definition
			std::string Owner;       // the kind a function or field belongs to, or the alias of a 'use'
			std::string File;        // the module path for 'use' (Kind::Module) and its definitions
			int Line = 0;            // 1-based, as in the lexer
			int Column = 0;          // 1-based byte column
			int Length = 0;          // bytes
		};

	private:
		struct Document
		{
			std::string Text;
			std::filesystem::path Path;
			double Version = 0;
		};

		struct ApiFunction
		{
			std::string Name;
			std::string Signature;
			std::string Returns;
			std::string Doc;
		};

		struct ApiMember
		{
			std::string Name;
			std::string Signature;
			std::string Type;   // a property's type, or a method's return type
			std::string Doc;
			bool IsProperty = false;
		};

		struct ApiType
		{
			std::string Name;
			std::string Doc;
			std::vector<ApiMember> Members;
		};

		struct ApiPhrase
		{
			std::string Pattern;
			std::string Returns;
			std::string Doc;
			bool YieldsToCalls = false; // see VM::RegisterPhrase
		};

	private:
		Json Initialize(const Json& params);
		Json Completion(const Json& params);
		Json Hover(const Json& params);
		Json Definition(const Json& params);
		Json DocumentSymbols(const Json& params);
		Json SignatureHelp(const Json& params);
		Json References(const Json& params);
		// The whole document laid out by FormatScript, or a reason in outError.
		Json Format(const Json& params, std::string& outError);
		// textDocument/codeAction: the quick fixes of this script's mistakes on the asked lines.
		Json CodeActions(const Json& params);
		static Json MistakeRange(const std::string& text, const CompileError& mistake);
		static Json WarningRange(const std::string& text, const CompileError& warning);
		// Rename and its check: a reason in outError when the name can't be renamed (then the reply is
		// an error the editor shows).
		Json PrepareRename(const Json& params, std::string& outError);
		Json Rename(const Json& params, std::string& outError);
		Json PublishDiagnostics(const std::string& uri);

		// A VM that checks 'path' as the engine would: the engine's phrases known, 'use' reading open
		// documents first.
		void SetUpChecker(VM& vm, const std::filesystem::path& path) const;
		// Which variable each name in a document means (VM::FindNameUses), and the use under a position
		// ("textDocument" and "position" of a request), or nullptr.
		const NameUse* NameUseAt(const Document& document, const Json& params, std::vector<NameUse>& outUses,
			std::vector<CompileError>& outMistakes) const;
		// Why the name under the request's position can't be renamed, or "" (then outUses and outUse are
		// that document's uses and the one under the cursor).
		std::string CheckRenamable(const Document& document, const Json& params, std::vector<NameUse>& outUses, NameUse& outUse) const;
		// 'trigger door opend' where no script that can hear it has 'when door opend' or 'wait for door
		// opend' (Roadmap 3.0 item 6). In a project that is every script in its asset folder, Python ones
		// included; elsewhere, this script and the ones it uses. None when that can't all be read.
		std::vector<CompileError> FindEventWarnings(const std::filesystem::path& path, const std::string& text) const;
		// The events a script file listens for, read again only when its time or size changes.
		const std::set<std::string>* ListenedInFile(const std::filesystem::path& path, bool python) const;
		// Why renaming a script-level name could break another script of the game, or "".
		std::string CheckNoOtherScriptNeeds(const Document& document, const std::string& oldName) const;

		void LoadApi(const std::filesystem::path& file);
		bool ReadScriptForUse(const std::filesystem::path& path, std::string& outSource) const;
		std::vector<Symbol> UsedSymbols(const std::filesystem::path& scriptPath, const std::string& source) const;
		// The diagnostics of the open documents that use 'changed', which may have changed what they show.
		void PublishDependents(const std::filesystem::path& changed, const std::string& skipUri, std::vector<Json>& replies);
		// What a name holds at a line, judged from the last 'set <name> to ...' above it: an engine type
		// ("Entity"), a built-in kind of value ("text", "list", "map", "vector", "number"), "kind:<Name>"
		// for a script's kind, or "" when it can't be told.
		std::string GuessType(const std::vector<std::string_view>& lines, const std::vector<Symbol>& symbols, const std::string& name, int lineIndex, int depth) const;
		std::string ExpressionType(std::string_view expression, const std::vector<std::string_view>& lines, const std::vector<Symbol>& symbols, int lineIndex, int depth) const;
		// The first type in an API type text ("Entity | None") that completion can use.
		std::string TypeFromApi(std::string_view type) const;
		const ApiType* FindApiType(std::string_view name) const;
		const Document* FindDocument(const std::string& uri) const;

	private:
		Options m_Options;
		std::map<std::string, Document> m_Documents;
		std::vector<ApiFunction> m_ApiFunctions;
		std::vector<ApiType> m_ApiTypes;
		std::vector<ApiPhrase> m_ApiPhrases;
		// FindEventWarnings' memory of each script file's listened events. The server answers one
		// request at a time, so the checks that fill it never overlap.
		struct ListenedFile
		{
			std::filesystem::file_time_type Time;
			uintmax_t Size = 0;
			std::set<std::string> Names;
		};
		mutable std::map<std::string, ListenedFile> m_ListenedFiles;
		std::string m_ApiError;
		bool m_Initialized = false;
		bool m_Strict = false; // initializationOptions.strict: warnings are sent as mistakes
		bool m_ShutdownRequested = false;
		bool m_ExitRequested = false;
	};

	// The definitions in a script (functions, phrases, kinds, constants, variables, parameters and
	// 'use' lines), in order. Works on scripts with mistakes too.
	std::vector<LanguageServer::Symbol> FindScriptSymbols(const std::string& source);

	// One entry of a script's outline: what an editor lists to jump around a script. Lines are 1-based,
	// columns 1-based bytes, as the lexer counts them.
	struct OutlineItem
	{
		enum class Kind
		{
			Function,
			Phrase,
			KindType,
			Handler,
			Variable,
			Constant,
			Property, // 'property name ... end' inside a kind: read like a field, worked out by its block.
			Contract  // 'contract Name ... end': its 'needs' lines are its children.
		};
		Kind ItemKind = Kind::Function;
		std::string Name;   // "jump", "deal (amount) damage", "Door", "when hit with damage", "speed".
		std::string Detail; // Its signature or first value, as hover shows it.
		int StartLine = 0;
		int EndLine = 0;    // The line of its 'end' (or StartLine for a variable).
		int NameLine = 0;
		int NameColumn = 0;
		int NameLength = 0;
		std::vector<OutlineItem> Children; // A kind's fields, functions and handlers.
	};

	// The functions, phrases, kinds (with their fields, functions and handlers), 'when' handlers,
	// script variables and constants of a script, in order, from its tokens, without compiling it, so
	// a script with mistakes still has an outline. Code inside functions and handlers is not listed.
	std::vector<OutlineItem> FindOutline(const std::string& source);

}
